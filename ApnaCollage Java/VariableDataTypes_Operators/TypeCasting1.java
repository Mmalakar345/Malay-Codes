package VariableDataTypes_Operators;

public class TypeCasting1 {
    public static void main(String[] args) {
        
        int num = 10;
        long num2 = num;
        System.out.println(num2);

        float num3 = num;
        System.out.println(num3);

        double num4 = num;
        System.out.println(num4);

        byte number = 5;
        int number1 = number;
        System.out.println(number1);
    }
}
