package VariableDataTypes_Operators;

public class Arithmatic {
    public static void main(String[] args) {
        // Simple Addition
        System.out.println("5 + 2 = "+ (5 + 2));
        //Simple Subtraction
        System.out.println("7 - 11 = "+ (7 - 11));
        // Simple multiplicaton
        System.out.println("5 * 2 = "+ 5  * 2);
        // Simple division
        System.out.println("6 / 2 = "+ 6 / 2);
        // Simple remender
        System.out.println("5 % 2 = "+ 5 % 2);

        // Integer division
        System.out.println("3 / 2 ans = "+3 / 2);
        // this division ignoge (0.000000000) point after value

        

        // double division
        // don't care nominator - denominator - bot are double. let's show
        System.out.println("3.0 / 2 = "+ (3.0 / 2));
        System.out.println("2 / 5.0 = "+ (2 / 5.0));
        System.out.println("7.0 / 3.0 = "+ (7.0 / 3.0));

    }
}
